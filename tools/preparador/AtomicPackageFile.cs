using System.Security.Cryptography;

namespace ComercialInsight.Preparador;

/// <summary>Only a fully validated sibling file can replace the selected destination.</summary>
internal sealed class AtomicPackageFile : IDisposable
{
    private readonly string target;
    private readonly string? originalSignature;
    private bool published;
    private readonly Action<string>? diagnostic;
    internal string TemporaryPath { get; }
    internal string BodyPath { get; }
    internal AtomicPackageFile(string target, Action<string>? diagnostic = null)
    {
        this.diagnostic = diagnostic;
        this.target = Path.GetFullPath(target);
        string directory = Path.GetDirectoryName(this.target) ?? throw new InvalidOperationException("Pasta de destino inválida.");
        if (!Directory.Exists(directory)) throw new InvalidOperationException("A pasta de destino não existe.");
        string unique = ".ci-" + Guid.NewGuid().ToString("N");
        TemporaryPath = Path.Combine(directory, unique + ".package.partial"); BodyPath = Path.Combine(directory, unique + ".body.partial");
        originalSignature = File.Exists(this.target) ? Signature(this.target) : null;
    }
    internal PackageValidationSummary Publish()
    {
        if (published) throw new InvalidOperationException("Este pacote já foi publicado no destino.");
        var result = PackageIntegrity.Validate(TemporaryPath);
        if (originalSignature != null)
        {
            if (!File.Exists(target) || Signature(target) != originalSignature)
                throw new InvalidOperationException("O arquivo de destino mudou durante a preparação. Ele foi preservado; escolha outro nome e prepare novamente.");
            // Same-directory NTFS replacement is atomic. Never delete the old destination first.
            File.Replace(TemporaryPath, target, null);
        }
        else
        {
            // overwrite:false also protects a file created by another process after preparation began.
            if (File.Exists(target)) throw new InvalidOperationException("Outro arquivo foi criado no destino durante a preparação. Ele foi preservado; escolha outro nome.");
            File.Move(TemporaryPath, target);
        }
        published = true; return result;
    }
    private static string Signature(string path)
    {
        using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read);
        return Convert.ToHexString(SHA256.HashData(stream));
    }
    public void Dispose()
    {
        // Paths are generated by this instance; no user file or another attempt's partial is removed.
        foreach (string path in new[] { TemporaryPath, BodyPath })
            try { if (File.Exists(path)) File.Delete(path); }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            { diagnostic?.Invoke("package.cleanup result=warning type=" + ex.GetType().Name + "; somente um temporário desta tentativa foi mantido"); }
    }
    internal static void SelfTest()
    {
        string folder = Path.Combine(Path.GetTempPath(), "ci-atomic-test-" + Guid.NewGuid().ToString("N")); Directory.CreateDirectory(folder);
        string target = Path.Combine(folder, "test.ci.ndjson"), marker = Path.Combine(folder, "unowned.partial");
        byte[] original = PackageIntegrity.TestFixture("Original"), replacement = PackageIntegrity.TestFixture("Replacement");
        try
        {
            File.WriteAllBytes(target, original); File.WriteAllText(marker, "Preserve another attempt");
            string partial;
            using (var failed = new AtomicPackageFile(target))
            {
                partial = failed.TemporaryPath; File.WriteAllBytes(failed.TemporaryPath, replacement[..^5]); File.WriteAllText(failed.BodyPath, "incomplete");
                bool rejected = false;
                try { failed.Publish(); } catch (InvalidDataException) { rejected = true; }
                if (!rejected || !File.ReadAllBytes(target).SequenceEqual(original)) throw new InvalidOperationException("Falha de exportação substituiu o pacote anterior.");
            }
            if (File.Exists(partial) || !File.Exists(marker)) throw new InvalidOperationException("Limpeza de temporários removeu arquivos indevidos.");
            using (var valid = new AtomicPackageFile(target)) { File.WriteAllBytes(valid.TemporaryPath, replacement); valid.Publish(); }
            if (!File.ReadAllBytes(target).SequenceEqual(replacement)) throw new InvalidOperationException("Substituição atômica não publicou o pacote validado.");
            using (var changed = new AtomicPackageFile(target))
            {
                File.WriteAllBytes(changed.TemporaryPath, original); File.WriteAllBytes(target, original);
                bool rejected = false;
                try { changed.Publish(); } catch (InvalidOperationException) { rejected = true; }
                if (!rejected || !File.ReadAllBytes(target).SequenceEqual(original)) throw new InvalidOperationException("Mudança concorrente no destino não foi preservada.");
            }
        }
        finally
        {
            // Every path is a fixed child of this test's newly created folder.
            foreach (string path in new[] { target, marker }) if (File.Exists(path)) File.Delete(path);
            Directory.Delete(folder);
        }
    }
}
